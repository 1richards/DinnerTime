/**
 * Stable identifier per template, used as the SOURCE OF TRUTH for upserts
 * during seed-templates and to de-duplicate seeds-per-user during onboarding.
 * Format: `{cuisine-lowercase}:{title-slug}`.
 */
export function templateKey(r: { cuisine_type: string; title: string }): string {
  const slug = r.title
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, '-')
    .replace(/^-|-$/g, '');
  return `${r.cuisine_type.toLowerCase()}:${slug}`;
}
